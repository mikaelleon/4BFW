-- The bot's SQLite schema (user_version 16, see src/db.js) in Postgres.
--
-- Type choices:
--   * Timestamps are Unix milliseconds, as in SQLite, so they are bigint.
--   * On/off settings stay integer 0/1, so the existing queries and checks keep their meaning.
--   * Discord IDs and keyed hashes are text.
--   * Row ids are identity columns that still accept an explicit value, so a data copy keeps every id.

CREATE TABLE guilds (
  guild_id             text PRIMARY KEY,
  channel_id           text,
  log_channel_id       text,
  role_id              text,
  sticky_id            text,
  cooldown             integer NOT NULL DEFAULT 30,
  warn_limit           integer NOT NULL DEFAULT 3,
  welcome_dm           integer NOT NULL DEFAULT 0,
  counter              integer NOT NULL DEFAULT 0,
  mod_role_id          text,
  online_role_id       text,
  online_notified_at   bigint,
  report_limit         integer NOT NULL DEFAULT 3,
  warn_expiry_days     integer NOT NULL DEFAULT 0,
  highlight_channel_id text,
  highlight_period     text    NOT NULL DEFAULT 'off',
  highlight_daily_at   bigint,
  highlight_weekly_at  bigint,
  self_delete_minutes  integer NOT NULL DEFAULT 10,
  retention_days       integer NOT NULL DEFAULT 0,
  approval_mode        integer NOT NULL DEFAULT 0,
  filter_action        text    NOT NULL DEFAULT 'reject',
  block_invites        integer NOT NULL DEFAULT 0,
  block_links          integer NOT NULL DEFAULT 0,
  poll_hours           integer NOT NULL DEFAULT 0,
  featured_channel_id  text,
  featured_threshold   integer NOT NULL DEFAULT 5,
  min_join_days        integer NOT NULL DEFAULT 0,
  min_account_days     integer NOT NULL DEFAULT 0,
  daily_cap            integer NOT NULL DEFAULT 0,
  dup_hours            integer NOT NULL DEFAULT 24,
  owner_pin            text,
  auto_thread          integer NOT NULL DEFAULT 0,
  paused_until         bigint,
  pause_reason         text,
  quiet_start          integer,
  quiet_end            integer,
  pause_hold           integer NOT NULL DEFAULT 0,
  quiet_hold           integer NOT NULL DEFAULT 0
);

CREATE TABLE confessions (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id            text    NOT NULL,
  number              integer NOT NULL,
  author_id           text    NOT NULL,
  channel_id          text,
  message_id          text,
  content             text    NOT NULL,
  status              text    NOT NULL DEFAULT 'posted',
  created_at          bigint  NOT NULL,
  has_image           integer NOT NULL DEFAULT 0,
  rendered            text,
  color               integer,
  tag                 text,
  is_poll             integer NOT NULL DEFAULT 0,
  sub_id              integer,
  author_key          text,
  purged_at           bigint,
  reply_to            text,
  cw                  text,
  poll_hours          integer NOT NULL DEFAULT 0,
  poll_ends_at        bigint,
  poll_closed_at      bigint,
  hold_reason         text,
  featured_channel_id text,
  featured_message_id text,
  thread_id           text,
  thread_root         bigint,
  op_tag              integer NOT NULL DEFAULT 0,
  alias               text,
  posted_at           bigint,
  release_tries       integer NOT NULL DEFAULT 0
);
CREATE INDEX idx_conf_author ON confessions (guild_id, author_id, created_at);
CREATE INDEX idx_conf_message ON confessions (guild_id, message_id);
CREATE UNIQUE INDEX idx_conf_subid ON confessions (guild_id, sub_id);
CREATE INDEX idx_confessions_guild_created ON confessions (guild_id, created_at);

CREATE TABLE confession_images (
  confession_id bigint PRIMARY KEY,
  name          text  NOT NULL,
  data          bytea NOT NULL
);

CREATE TABLE warnings (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id      text   NOT NULL,
  user_id       text   NOT NULL,
  confession_id bigint,
  reason        text,
  created_at    bigint NOT NULL
);

CREATE TABLE bans (
  guild_id   text   NOT NULL,
  user_id    text   NOT NULL,
  reason     text,
  banned_by  text,
  created_at bigint NOT NULL,
  expires_at bigint,
  dm_id      text,
  PRIMARY KEY (guild_id, user_id)
);

CREATE TABLE reports (
  confession_id bigint NOT NULL,
  reporter_id   text   NOT NULL,
  reason        text,
  created_at    bigint NOT NULL,
  PRIMARY KEY (confession_id, reporter_id)
);

CREATE TABLE mod_notes (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id      text   NOT NULL,
  user_id       text   NOT NULL,
  confession_id bigint,
  note          text   NOT NULL,
  moderator_id  text   NOT NULL,
  created_at    bigint NOT NULL
);
CREATE INDEX idx_notes_user ON mod_notes (guild_id, user_id);

CREATE TABLE tag_channels (
  guild_id   text NOT NULL,
  tag        text NOT NULL,
  channel_id text NOT NULL,
  PRIMARY KEY (guild_id, tag)
);

CREATE TABLE reactions (
  confession_id bigint NOT NULL,
  user_id       text   NOT NULL,
  kind          text   NOT NULL,
  PRIMARY KEY (confession_id, user_id)
);

CREATE TABLE poll_options (
  confession_id bigint  NOT NULL,
  idx           integer NOT NULL,
  label         text    NOT NULL,
  PRIMARY KEY (confession_id, idx)
);

CREATE TABLE poll_votes (
  confession_id bigint  NOT NULL,
  user_id       text    NOT NULL,
  idx           integer NOT NULL,
  PRIMARY KEY (confession_id, user_id)
);

CREATE TABLE appeals (
  warning_id  bigint PRIMARY KEY,
  guild_id    text   NOT NULL,
  user_id     text   NOT NULL,
  message     text,
  status      text   NOT NULL DEFAULT 'open',
  resolved_by text,
  created_at  bigint NOT NULL
);

CREATE TABLE ban_appeals (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id    text   NOT NULL,
  user_key    text   NOT NULL,
  dm_id       text,
  message     text,
  status      text   NOT NULL DEFAULT 'open',
  resolved_by text,
  created_at  bigint NOT NULL,
  resolved_at bigint
);
CREATE INDEX idx_banappeal_user ON ban_appeals (guild_id, user_key);

CREATE TABLE filter_rules (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id   text   NOT NULL,
  kind       text   NOT NULL,
  pattern    text   NOT NULL,
  created_at bigint NOT NULL
);
CREATE INDEX idx_filter_guild ON filter_rules (guild_id);

CREATE TABLE user_prefs (
  user_id    text PRIMARY KEY,
  notify_off integer NOT NULL DEFAULT 0,
  preview    integer NOT NULL DEFAULT 0
);

CREATE TABLE thread_aliases (
  root_id  bigint  NOT NULL,
  user_key text    NOT NULL,
  alias    integer NOT NULL,
  PRIMARY KEY (root_id, user_key)
);

CREATE TABLE meta (
  key   text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE dm_cursor (
  user_id text PRIMARY KEY,
  last_id text NOT NULL
);

-- Supabase publishes the public schema through its web API. This data identifies anonymous senders, so close that door:
-- row level security with no policies, and no table rights for the API roles. The bot connects as the table owner,
-- which neither rule affects.
DO $$
DECLARE
  t text;
  r text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %I', r);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM %I', r);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM %I', r);
    END IF;
  END LOOP;
END $$;
